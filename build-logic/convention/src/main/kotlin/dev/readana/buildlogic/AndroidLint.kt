package dev.readana.buildlogic

import com.android.build.api.dsl.Lint
import org.gradle.api.Project

/**
 * Android Lint settings shared by every module. Warnings fail the build; anything that is
 * deliberately tolerated lives in `config/lint/lint.xml` with a justification.
 */
internal fun Project.configureLint(lint: Lint, checkDependencies: Boolean = false) {
    lint.apply {
        lintConfig = isolated.rootProject.projectDirectory.file("config/lint/lint.xml").asFile
        abortOnError = true
        warningsAsErrors = true
        checkReleaseBuilds = false
        this.checkDependencies = checkDependencies
        // HTML/XML/SARIF reports are always generated by AGP 9 (build/reports/lint-results-*.html).
    }
}
